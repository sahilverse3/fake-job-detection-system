class Job {
    String company;
    String email;
    String description;
    double salary;
    boolean asksMoney;

    Job(String company, String email, String description, double salary, boolean asksMoney) {
        this.company = company;
        this.email = email;
        this.description = description;
        this.salary = salary;
        this.asksMoney = asksMoney;
    }
}